import { chromium, expect } from "@playwright/test";
import assert from "node:assert/strict";
const browser=await chromium.launch({channel:"chrome",headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();const errors=[];
page.on("pageerror",e=>errors.push(e.message));
try {
  await page.goto("http://127.0.0.1:3100",{waitUntil:"networkidle"});
  await page.locator('[name="username"]').fill("qa");
  await page.locator('[name="password"]').fill("test-password-12345");
  await page.getByRole("button",{name:"登录游戏库",exact:true}).click();
  await expect(page.getByRole("heading",{name:/每一款游戏/})).toBeVisible();
  await page.getByRole("button",{name:"＋ 登记游戏",exact:true}).first().click();
  await page.locator('[name="title"]').fill("QA 浏览器测试游戏");
  await page.locator('[name="originalTitle"]').fill("Browser Verification");
  await page.locator('[name="genre"]').fill("探索冒险");
  await page.locator('[name="status"]').selectOption("BACKLOG");
  await page.locator('[name="hours"]').fill("12.5");
  await page.locator('[name="memo"]').fill("通过浏览器实际填写并保存的测试记录。");
  await page.screenshot({path:"engineering/ui-editor-desktop.png",fullPage:true});
  await page.getByRole("button",{name:"保存游戏",exact:true}).click();
  await expect(page.getByRole("heading",{name:"QA 浏览器测试游戏",exact:true})).toBeVisible();
  await page.screenshot({path:"engineering/ui-library-desktop.png",fullPage:true});
  await page.getByRole("heading",{name:"QA 浏览器测试游戏",exact:true}).click();
  await expect(page.getByText("12.5 h",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"修改条目",exact:true}).click();
  await page.locator('.item-overlay [name="hours"]').fill("15");
  await page.getByRole("button",{name:"保存条目",exact:true}).click();
  await expect(page.getByText("15.0 h",{exact:true})).toBeVisible();
  await page.locator('.detail-modal button[aria-label="关闭"]').click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,"手机页面横向溢出");
  await page.screenshot({path:"engineering/ui-library-mobile.png",fullPage:true});
  await page.getByRole("button",{name:"备份与恢复"}).click();
  const downloadPromise=page.waitForEvent("download");
  await page.getByRole("button",{name:"下载 JSON 备份",exact:true}).click();
  const download=await downloadPromise;await download.saveAs("engineering/ui-backup.json");
  await page.screenshot({path:"engineering/ui-backup-mobile.png",fullPage:true});
  assert.deepEqual(errors,[]);
  console.log("PASS UI_SMOKE desktop=create mobile=no-overflow item=edited backup=downloaded console_errors=0 screenshots=4");
} finally {await browser.close();}
